_WORD = re.compile(r"[a-zа-яё0-9]+", re.IGNORECASE)


def _tokens(text: str) -> list[str]:
    return [w.replace("ё", "е") for w in _WORD.findall(text.lower())]


def ask(question: str, role: str | None = None) -> dict[str, Any]:
    q = question.lower().replace("ё", "е")
    tokens = _tokens(question)
    scored: list[tuple[float, int, int]] = []
    for idx, (_, roles, _title, keys, _answer) in enumerate(KB):
        score = 0.0
        for key in keys:
            k = key.replace("ё", "е")
            if " " in k:
                score += 2.0 if k in q else 0.0
            elif len(k) <= 3:
                score += 1.0 if k in tokens else 0.0
            else:
                stem = k[: max(4, len(k) - 2)]
                score += 1.0 if any(t.startswith(stem) for t in tokens) else 0.0
        if score and role and role in roles:
            score += 0.5
        if score:
            scored.append((score, -idx, idx))
    scored.sort(reverse=True)
    hits = [KB[i] for _, _, i in scored[:2]]
    if not hits:
        return {"answer": FALLBACK, "topic": None, "related": [], "matched": False}
    best = hits[0]
    return {
        "answer": best[4],
        "topic": best[2],
        "related": [h[2] for h in hits[1:]],
        "matched": True,
    }


